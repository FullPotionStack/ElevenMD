import { test, expect } from '@playwright/test'

for (const sequence of [['Task list', 'Bullet list'], ['Task list', 'Numbered list'], ['Bullet list', 'Task list'], ['Numbered list', 'Task list'], ['Bullet list', 'Numbered list'], ['Numbered list', 'Bullet list']]) {
  test(`list conversion stays consistent: ${sequence.join(' → ')}`, async ({ page }) => {
    await page.goto('/')
    await page.locator('.tiptap').fill('Ship the note')
    await page.keyboard.press('Control+a')
    for (const name of sequence) await page.getByRole('button', { name, exact: true }).click()
    const task = sequence.at(-1) === 'Task list'
    await expect(page.locator('.tiptap input[type=checkbox]')).toHaveCount(task ? 1 : 0)
    await expect(page.locator('.tiptap li')).toHaveCount(1)
    await page.getByRole('button', { name: 'Source', exact: true }).click()
    const source = await page.locator('#source').inputValue()
    console.log(JSON.stringify({ sequence, source }))
    expect(source).not.toMatch(/\\\[[ x]\]|\[[ x]\].*\[[ x]\]/)
    if (task) expect(source).toMatch(/^- \[ \] Ship the note/)
    else expect(source).not.toContain('[ ]')
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await expect(page.locator('#preview li')).toHaveCount(1)
    await expect(page.locator('#preview input[type=checkbox]')).toHaveCount(task ? 1 : 0)
    await expect(page.locator('#preview')).not.toContainText('[ ]')
    await expect(page.locator('#preview li')).toContainText('Ship the note')
    await page.getByRole('button', { name: 'Formatted', exact: true }).click()
    await expect(page.locator('.tiptap li')).toHaveCount(1)
    await expect(page.locator('.tiptap input[type=checkbox]')).toHaveCount(task ? 1 : 0)
  })
}

test('empty task survives Preview, source reload, and formatted parsing', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Task list', exact: true }).click()
  await expect(page.locator('.tiptap input[type=checkbox]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(page.locator('#preview input[type=checkbox]')).toHaveCount(1)
  await expect(page.locator('#preview')).not.toContainText('[ ]')
  await page.getByRole('button', { name: 'Source', exact: true }).click()
  await page.locator('#source').fill('- [x]\n')
  await page.getByRole('button', { name: 'Formatted', exact: true }).click()
  await expect(page.locator('.tiptap input[type=checkbox]')).toBeChecked()
})

for (const markdown of ['- [ ]\n- [x] Finished\n- [ ]\n', '- [x] Finished\n- [ ]\n- [ ] Pending\n']) {
  test(`mixed empty and nonempty tasks remain one list: ${JSON.stringify(markdown)}`, async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: 'Source', exact: true }).click()
    await page.getByRole('textbox', { name: 'Markdown source' }).fill(markdown)
    await page.getByRole('button', { name: 'Formatted', exact: true }).click()
    await expect(page.locator('.tiptap input[type=checkbox]')).toHaveCount(3)
    await expect(page.locator('.tiptap > ul[data-type=taskList]')).toHaveCount(1)
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await expect(page.locator('#preview input[type=checkbox]')).toHaveCount(3)
    await expect(page.locator('#preview > ul')).toHaveCount(1)
  })
}

